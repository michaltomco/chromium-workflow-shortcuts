const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { connect, waitFor } = require('./browser-client.cjs');
// Use only a disposable profile on a virtual display (tests/x11-keys.c).
const base = process.env.CHROMIUM_DEBUG_URL || 'http://127.0.0.1:18765';
assert(process.env.SPLIT_TEST_KEY_HELPER, 'Set SPLIT_TEST_KEY_HELPER');
const key = (letter, shift = false) => execFileSync(process.env.SPLIT_TEST_KEY_HELPER,
  shift ? ['Alt_L', 'Shift_L', letter] : ['Alt_L', letter]);
(async () => {
  const targets = await (await fetch(base + '/json/list')).json();
  const page = await connect(targets.find(t => t.url.includes('/options.html')));
  const setup = await connect(targets.find(t => t.url === 'chrome://extensions/'));
  const windows = [];
  const evaluate = page.evaluate;
  const presets = () => evaluate('(async()=> (await chrome.storage.local.get("groupPresets")).groupPresets)()');
  const state = () => evaluate('(async()=>({refs:(await chrome.storage.local.get("managedTabGroups")).managedTabGroups||{},tabs:await chrome.tabs.query({}),groups:await chrome.tabGroups.query({}),window:await chrome.windows.getLastFocused()}))()');
  const save = async () => {
    await evaluate('document.querySelector("#save").click()');
    await waitFor(()=>evaluate('!saving && document.querySelector("#save").disabled && document.querySelector("#status").textContent.startsWith("Saved.")'));
  };
  try {
    for (const [commandName, keybinding] of [['toggle-group-mute', 'Alt+M'], ['mute-collapse-next-group', 'Alt+Shift+M'], ['toggle-preset-2', 'Alt+Y'], ['mute-preset-2', 'Alt+Shift+Y']]) {
      await setup.evaluate(`chrome.developerPrivate.updateExtensionCommand(${JSON.stringify({ extensionId: 'ejkfmjmeohnjjcljkfojojhkfaehaanf', commandName, keybinding })})`);
    }
    const legacy = ['https://www.messenger.com/t/legacy', 'https://web.whatsapp.com/', 'https://discord.com/channels/@me'];
    await evaluate(`chrome.storage.local.set({chatGroupUrls:${JSON.stringify(legacy)}})`);
    await evaluate('chrome.storage.local.remove(["groupPresets","managedTabGroups","chatTabGroup"])');
    await page.send('Page.reload');
    await waitFor(()=>evaluate('document.querySelector("#chat-urls")?.value.includes("/t/legacy")'));
    const w = await evaluate('chrome.windows.create({url:"about:blank",focused:true})'); windows.push(w.id);
    const outside = w.tabs[0].id;
    key('m');
    await waitFor(async()=> (await state()).refs.chat);
    let snapshot = await state(); const chatId = snapshot.refs.chat.id;
    await waitFor(async()=> (await state()).tabs.filter(t=>t.groupId===chatId).length===3);
    const chatTabs = (await state()).tabs.filter(t=>t.groupId===chatId).map(t=>t.id);
    const oldRef = await evaluate('(async()=> (await chrome.storage.local.get("chatTabGroup")).chatTabGroup)()');
    await evaluate(`chrome.storage.local.set({chatTabGroup:${JSON.stringify(oldRef)}})`);
    await evaluate('chrome.storage.local.remove("managedTabGroups")');
    await evaluate('document.querySelector("#add-group").click()');
    await evaluate(`(()=>{const card=document.querySelector('[data-slot="2"]');const name=card.querySelector('.preset-name');name.value='Research';name.dispatchEvent(new Event('input'));const urls=card.querySelector('.preset-urls');urls.value='https://discord.com/channels/@me\\nhttps://www.messenger.com/t/research';urls.dispatchEvent(new Event('input'));const color=card.querySelector('.preset-color');color.value='purple';color.dispatchEvent(new Event('change'))})()`);
    await save();
    const configured = await presets(), research = configured.find(p=>p.slot===2);
    assert.equal(configured[0].id, 'chat'); assert.deepEqual(configured[0].urls, legacy);
    assert.equal(research.name, 'Research'); assert.equal(research.color, 'purple');
    assert.equal(await evaluate('document.querySelector(\'[data-slot="2"] [data-key="toggle"]\').textContent'), 'Alt+Y');
    await page.send('Page.reload');
    await waitFor(()=>evaluate('document.querySelectorAll(".preset-card").length===2'));
    assert.equal(await evaluate('document.querySelector(\'[data-slot="2"] .preset-name\').value'), 'Research');
    console.log('PASS: legacy Chat URLs/identity migrate; name, color, URL list and native keys persist');
    await evaluate(`chrome.windows.update(${w.id},{focused:true})`);
    key('y');
    await waitFor(async()=> { const s=await state();return s.refs[research.id] && s.tabs.filter(t=>t.groupId===s.refs[research.id].id).length===2; });
    snapshot = await state(); const researchId = snapshot.refs[research.id].id;
    assert.notEqual(researchId, chatId);
    assert.deepEqual(snapshot.tabs.filter(t=>t.groupId===chatId).map(t=>t.id), chatTabs);
    assert(snapshot.tabs.filter(t=>t.groupId===researchId).every(t=>!chatTabs.includes(t.id)));
    assert.equal(snapshot.groups.find(g=>g.id===researchId).color, 'purple');
    key('y');
    await waitFor(async()=> (await state()).groups.find(g=>g.id===researchId).collapsed);
    snapshot = await state(); assert(snapshot.tabs.filter(t=>t.groupId===researchId).every(t=>t.mutedInfo.muted));
    assert(snapshot.tabs.filter(t=>t.groupId===chatId).every(t=>!t.mutedInfo.muted));
    key('y');
    await waitFor(async()=> !(await state()).groups.find(g=>g.id===researchId).collapsed);
    await evaluate(`chrome.tabs.update(${chatTabs[0]},{active:true})`);
    key('y', true);
    await waitFor(async()=> (await state()).groups.find(g=>g.id===researchId).collapsed);
    assert((await state()).tabs.find(t=>t.id===chatTabs[0]).active);
    key('m');
    await waitFor(async()=> (await state()).groups.find(g=>g.id===chatId).collapsed);
    key('m');
    await waitFor(async()=> !(await state()).groups.find(g=>g.id===chatId).collapsed);
    assert.deepEqual((await state()).tabs.filter(t=>t.groupId===chatId).map(t=>t.id), chatTabs);
    console.log('PASS: independent native toggles/quiet keys, overlapping sites do not steal tabs, existing Chat group retained');
    await evaluate('document.querySelector("#add-group").click();document.querySelector("#save").click()');
    await waitFor(()=>evaluate('document.querySelector("#status").textContent.includes("Add at least one")'));
    assert.equal((await presets()).length, 2);
    await evaluate('document.querySelector(\'[data-slot="3"] .preset-remove\').click()');
    await evaluate('(()=>{const input=document.querySelector(\'[data-slot="2"] .preset-name\');input.value="Chat";input.dispatchEvent(new Event("input"));document.querySelector("#save").click()})()');
    await waitFor(()=>evaluate('document.querySelector("#status").textContent.includes("different name")'));
    await evaluate('(()=>{const input=document.querySelector(\'[data-slot="2"] .preset-name\');input.value="Research";input.dispatchEvent(new Event("input"))})()');
    const beforeRemoval = (await state()).tabs.map(t=>t.id);
    await evaluate('document.querySelector(\'[data-slot="2"] .preset-remove\').click()'); await save();
    assert.deepEqual((await state()).tabs.map(t=>t.id), beforeRemoval);
    key('y'); await new Promise(resolve=>setTimeout(resolve,150));
    assert.deepEqual((await state()).tabs.map(t=>t.id), beforeRemoval);
    console.log('PASS: invalid presets rejected; removing a preset keeps its browser tabs and disables its action');
    await evaluate('document.querySelector("#add-group").click()');
    await evaluate('(()=>{const card=document.querySelector(\'[data-slot="2"]\');const input=card.querySelector(".preset-name");input.value="Projects";input.dispatchEvent(new Event("input"));const urls=card.querySelector(".preset-urls");urls.value="https://web.whatsapp.com/";urls.dispatchEvent(new Event("input"))})()'); await save();
    const projects = (await presets()).find(p=>p.slot===2); assert.notEqual(projects.id, research.id);
    await evaluate(`chrome.windows.update(${w.id},{focused:true})`); key('y');
    await waitFor(async()=> (await state()).refs[projects.id]);
    snapshot = await state(); const projectsId=snapshot.refs[projects.id].id;
    assert.notEqual(projectsId,researchId); assert.notEqual(projectsId,chatId);
    assert.deepEqual(snapshot.tabs.filter(t=>t.groupId===chatId).map(t=>t.id),chatTabs);
    assert(snapshot.groups.some(g=>g.id===researchId));
    await evaluate('(()=>{const card=document.querySelector(\'[data-slot="2"]\');const input=card.querySelector(".preset-name");input.value="Work stuff";input.dispatchEvent(new Event("input"));const color=card.querySelector(".preset-color");color.value="orange";color.dispatchEvent(new Event("change"))})()'); await save();
    key('y'); await waitFor(async()=> (await state()).groups.find(g=>g.id===projectsId).collapsed);
    key('y'); await waitFor(async()=> (await state()).groups.some(g=>g.id===projectsId&&g.title==='Work stuff'&&g.color==='orange'&&!g.collapsed));
    console.log('PASS: reused shortcut slots get new preset identities; rename/color changes retain the correct group');
    await evaluate('document.querySelectorAll(".preset-remove").forEach(button=>button.click())'); await save();
    assert.deepEqual(await presets(),[]);
    const noPresetsTabs=(await state()).tabs.map(t=>t.id);
    key('m');key('y'); await new Promise(resolve=>setTimeout(resolve,150));
    assert.deepEqual((await state()).tabs.map(t=>t.id),noPresetsTabs);
    await evaluate('document.querySelector("#add-group").click()');
    for(let i=1;i<10;i++)await evaluate('document.querySelector("#add-group").click()');
    assert.equal(await evaluate('document.querySelector("#add-group").disabled'),true);
    assert.equal(await evaluate('document.querySelectorAll(".preset-card").length'),10);
    await evaluate('document.querySelector("#reset").click()'); await save();
    assert.equal((await presets()).length,1);
    console.log('PASS: empty preset list, ten stable shortcut slots and factory defaults');
  } finally {
    for(const id of windows) await evaluate(`chrome.windows.remove(${id})`).catch(()=>{});
    page.ws.close();setup.ws.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1});
