const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('shortcut-config.js', 'utf8'), context);
const config = context.WorkflowShortcuts;
assert.equal(config.normalize('shift+alt+p'), 'Alt+Shift+P');
assert.equal(config.normalize('t'), 'T');
assert.equal(config.normalize(''), '');
assert.throws(() => config.normalize('Ctrl+Ctrl+K'));
assert.throws(() => config.normalize('Alt+DoesNotExist'));
assert.equal(config.fromEvent({ key: 'Shift' }), null);
assert.equal(config.fromEvent({ key: 'P', altKey: true, shiftKey: true }), 'Alt+Shift+P');
config.validate(config.defaults());
const duplicate = config.defaults(); duplicate.desktop.back = duplicate.desktop.forward;
assert.throws(() => config.validate(duplicate), /already assigned/);
assert.throws(() => config.validate(config.defaults(), [{ name: 'conflict', description: 'Previous tab', shortcut: 'Alt+Shift+K' }]), /Chromium/);
const plain = config.defaults(); plain.desktop.back = 'F';
assert.throws(() => config.validate(plain), /include Ctrl/);
assert.equal(config.resolve({ page: { videoFullscreen: '' } }).page.videoFullscreen, '');
assert.equal(config.resolve({ page: { videoFullscreen: 3 } }).page.videoFullscreen, 'Alt+P');
const lua = config.toHyprland(config.defaults());
assert(lua.includes('videoFullscreen = "ALT + P"'));
assert(lua.includes('pictureInPicture = "ALT + SHIFT + P"'));
console.log('PASS: recording normalization, validation, collisions, cleared settings, Hyprland export');
